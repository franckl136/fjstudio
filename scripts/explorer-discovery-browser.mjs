import assert from 'node:assert/strict';
import { randomBytes,randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { mkdtemp,mkdir,rename,rm,writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';
import { createPool } from '../src/config.ts';
import { Core,migrate } from '../src/core.ts';
import { createServer } from '../src/http.ts';
import { HumanAccess } from '../src/product-auth.ts';
import { humanCookie } from '../src/product-auth-routes.ts';
import { captureInternal } from '../src/explorer-store.ts';

const url=new URL(process.env.DATABASE_URL);
assert.equal(url.port,'55453');assert.equal(url.pathname,'/fjstudio_a1');
const dbName='fjstudio_a1_test_'+randomUUID().replaceAll('-',''),maintenance=createPool(url.href);
const repos=await mkdtemp(join(tmpdir(),'fjstudio-f08-fixtures-')),captures=await mkdtemp(join(tmpdir(),'fjstudio-f08-captures-'));
const notion=join(repos,'notion'),supabase=join(repos,'supabase');
const credential={kind:'operator',id:'operator-local',projectIds:['a','b'],token:randomBytes(32).toString('hex')},key=randomBytes(32);
let pool,server,browser,created=false;
try{
  await maintenance.query('CREATE DATABASE '+dbName+' TEMPLATE template0');created=true;
  url.pathname='/'+dbName;pool=createPool(url.href);await migrate(pool);
  await mkdir(notion);await mkdir(supabase);
  await writeFile(join(notion,'package.json'),JSON.stringify({dependencies:{'@notionhq/client':'0'}}));
  await writeFile(join(notion,'.gitignore'),'schema.sql\n');
  await writeFile(join(notion,'schema.sql'),'BROKEN IGNORED SQL');
  await mkdir(join(notion,'apps','ignore-me'),{recursive:true});
  await writeFile(join(notion,'apps','.gitignore'),'ignore-me/\n');
  await writeFile(join(notion,'apps','ignore-me','package.json'),'INVALID IGNORED JSON');
  await mkdir(join(notion,'migrations'));
  await writeFile(join(notion,'migrations','001_credentials.sql'),'BROKEN SENSITIVE SQL');
  await writeFile(join(notion,'.env.local'),'synthetic-unobserved-marker');
  await mkdir(join(supabase,'supabase','migrations'),{recursive:true});
  await writeFile(join(supabase,'package.json'),JSON.stringify({dependencies:{'@supabase/supabase-js':'0'}}));
  await writeFile(join(supabase,'supabase','migrations','001_schema.sql'),'CREATE TABLE public.ateliers(id int PRIMARY KEY); CREATE VIEW public.ateliers_visibles AS SELECT id FROM public.ateliers;');
  const targets=[{project:'a',key:'fixture-notion',directory:notion,remote:''},{project:'b',key:'fixture-supabase',directory:supabase,remote:''}];
  process.env.STUDIO_GIT_REPOSITORIES=JSON.stringify(targets);
  delete process.env.STUDIO_EXPLORER_CONNECTIONS;
  for(const p of targets)await pool.query('INSERT INTO project_repositories(project_id,repository_key,remote_url,registered_by) VALUES($1,$2,\'\',\'fixture\')',[p.project,p.key]);
  const access=new HumanAccess(pool,key,true),ticket=await access.begin(credential.token,credential);
  const admin=await access.finish(ticket.ticket,randomUUID(),'');
  server=createServer(new Core(pool),[credential],key,true);
  server.listen(0,'127.0.0.1');await once(server,'listening');
  const origin='http://127.0.0.1:'+server.address().port;
  browser=await chromium.launch({channel:process.platform==='win32'?'chrome':undefined,executablePath:process.env.STUDIO_QA_BROWSER,headless:true});
  const context=await browser.newContext({locale:'fr-FR'});
  await context.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
  await context.addCookies([{name:humanCookie,value:admin,url:origin,httpOnly:true,sameSite:'Strict'}]);
  const page=await context.newPage(),failures=[];
  page.setDefaultTimeout(5000);page.on('pageerror',err=>failures.push(err.message));
  const project=async(id)=>{await page.goto(origin+'/projects/'+id+'/database');};
  const sync=async(id)=>{await project(id);await page.getByRole('button',{name:'Actualiser depuis le code'}).click();};
  for(const viewport of [{width:1440,height:900},{width:390,height:844}]){
    await page.setViewportSize(viewport);
    await sync('a');
    const notice=page.locator('section').filter({has:page.getByRole('heading',{name:'Disponibilité du schéma'})});
    await notice.getByText(/Intégration Notion déclarée.*Aucun schéma SQL ou Prisma exploitable.*compte Notion n’a pas été vérifié/).waitFor();
    assert.doesNotMatch(await page.locator('main').innerText(),/maintenance|base interne|BROKEN|synthetic-unobserved-marker/i);
    await notice.scrollIntoViewIfNeeded();await page.screenshot({path:join(captures,'notion-'+viewport.width+'.png')});
    await notice.getByRole('link',{name:'importer un schéma de ce projet'}).click();
    await page.getByLabel('Nom de la source').waitFor({state:'visible'});
    await sync('b');
    await page.getByText('Source locale accessible · structure découverte dans le code',{exact:true}).waitFor();
    await page.getByRole('link',{name:'supabase/migrations',exact:true}).click();
    await page.getByRole('link',{name:'public.ateliers',exact:true}).waitFor();
    await page.getByRole('link',{name:'public.ateliers_visibles',exact:true}).waitFor();
    await page.getByRole('link',{name:'Diagramme relationnel'}).waitFor();
    await page.getByText(/Métadonnées extraites du code/).waitFor();
    assert.doesNotMatch(await page.locator('main').innerText(),/Connexion confirmée|Schéma importé/i);
    await page.getByRole('heading',{name:'Tables et vues'}).scrollIntoViewIfNeeded();
    await page.screenshot({path:join(captures,'supabase-'+viewport.width+'.png')});
  }
  await writeFile(join(notion,'package.json'),'INVALID LOCAL JSON');
  await sync('a');await page.getByText(/^Fichier illisible\. Vérifiez le format/).waitFor();
  await rename(notion,join(repos,'detached'));
  await sync('a');await page.getByText(/^Source indisponible\. Vérifiez que le dossier/).waitFor();
  await page.getByRole('link',{name:'importer un schéma de ce projet'}).click();
  await page.getByLabel('Nom de la source').fill('Manuel de recette');
  await page.getByLabel('Définition du schéma').fill('CREATE TABLE billets(id int PRIMARY KEY);');
  await page.getByRole('button',{name:'Importer la structure'}).click();
  await page.getByText(/Schéma importé · Import SQL/).waitFor();
  await page.getByRole('link',{name:'public.billets',exact:true}).waitFor();
  const inner=await captureInternal(pool);
  await page.goto(origin+'/database');await page.getByRole('heading',{name:'Catalogue interne du Studio'}).waitFor();
  await page.getByRole('link',{name:'Base interne du Studio',exact:true}).waitFor();
  assert.equal((await page.request.get(origin+'/api/projects/a/database?source='+inner.source)).status(),404);
  assert.deepEqual(failures,[]);console.log(JSON.stringify({result:'PASS',scenarios:['notion','supabase','fichier illisible','source indisponible','import','catalogue interne','exclusions'],viewports:['1440x900','390x844'],captures}));
}finally{
  await browser?.close();if(server)await new Promise(r=>server.close(r));await pool?.end();
  if(created)await maintenance.query('DROP DATABASE '+dbName);await maintenance.end();
  await rm(repos,{recursive:true,force:true});
}
