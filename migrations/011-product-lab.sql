CREATE TABLE product_lab_runs (
  id uuid PRIMARY KEY,
  project_id text NOT NULL REFERENCES projects(id),
  command_key uuid NOT NULL,
  source_key text NOT NULL,
  entry_path text NOT NULL,
  commit_sha text NOT NULL CHECK (commit_sha ~ '^[0-9a-f]{40}$'),
  source_digest text NOT NULL CHECK (source_digest ~ '^[0-9a-f]{64}$'),
  source_html bytea NOT NULL CHECK (octet_length(source_html) BETWEEN 1 AND 131072),
  inventory jsonb NOT NULL,
  profile text NOT NULL CHECK (profile IN ('structure','visual')),
  profile_version text NOT NULL,
  trigger_kind text NOT NULL CHECK (trigger_kind IN ('manual','on-change','interval')),
  actor_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  started_at timestamptz,
  finished_at timestamptz,
  worker text,
  state text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','running','finished')),
  verdict text CHECK (verdict IN ('PASS','PASS WITH RESERVATIONS','FAIL','NOT QUALIFIED')),
  result jsonb,
  result_sha text,
  screenshot bytea,
  screenshot_sha text,
  UNIQUE(project_id,command_key),
  CHECK (source_digest = encode(sha256(source_html),'hex')),
  CHECK ((state='finished') = (verdict IS NOT NULL AND finished_at IS NOT NULL AND result IS NOT NULL)),
  CHECK ((result IS NULL) = (result_sha IS NULL)),
  CHECK (result_sha IS NULL OR result_sha ~ '^[0-9a-f]{64}$'),
  CHECK ((screenshot IS NULL) = (screenshot_sha IS NULL)),
  CHECK (screenshot IS NULL OR octet_length(screenshot) BETWEEN 8 AND 524288 AND screenshot_sha = encode(sha256(screenshot),'hex'))
);
CREATE INDEX product_lab_project_history ON product_lab_runs(project_id,created_at DESC);
CREATE INDEX product_lab_queue ON product_lab_runs(state,created_at) WHERE state <> 'finished';
CREATE TABLE product_lab_rules (
  project_id text NOT NULL REFERENCES projects(id),
  source_key text NOT NULL,
  profile text NOT NULL CHECK (profile IN ('structure','visual')),
  mode text NOT NULL CHECK (mode IN ('on-change','interval')),
  enabled boolean NOT NULL DEFAULT true,
  interval_minutes integer NOT NULL CHECK (interval_minutes BETWEEN 5 AND 10080),
  revision uuid NOT NULL DEFAULT gen_random_uuid(),
  updated_by text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  next_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  last_commit text,
  last_status text,
  PRIMARY KEY(project_id,source_key,profile)
);
